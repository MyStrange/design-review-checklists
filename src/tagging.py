"""Подстраховка для тегов: «к кому идти с этим пунктом».

Тег пункту ставит нейросеть, но она ленится и почти всё помечает как "ux" —
с июня 2026 так пропали бейджики «Продакт», «Юрист», «SEO» и остальные.
Здесь живут правила по тексту пункта: если в нём прямым текстом сказано, к
какому специалисту идти, тег ставим сами.

Правила намеренно узкие: лучше пропустить пункт и оставить "ux", чем повесить
бейджик не по делу. Бейджик — редкая и потому заметная метка, а не подпись
к каждой строке.

Используется в двух местах:
- при разборе новой встречи (main.build_session) — чинит ленивый "ux";
- командой `python -m src.main --retag` — проходит по уже разобранным встречам.
"""
import re

# Порядок важен: побеждает первое совпавшее правило. Сверху — самые
# однозначные признаки, снизу — более широкие.
RULES = (
    ("legal", r"юрист|юридическ|персональн\w*\s+данн|согласи[ея]\s+на\s+обработ|"
              r"оферт|политик\w*\s+конфиденциальн|требован\w*\s+(закон|регулятор)|152-?фз"),
    ("seo", r"\bseo\b|сео-|поисков\w*\s+(выдач|запрос|продвиж|робот)|индексац|"
            r"индексир|метатег|мета-тег|ключев\w*\s+слов"),
    ("branding", r"брендинг|бренд-команд|бренд-?бук|гайдлайн|фирменн\w*\s+стил|"
                 r"айдентик|бренд\w*\s+(команд|отдел|стил)"),
    ("research", r"исследован|юзабилити|usability|кастдев|custdev|"
                 r"глубинн\w*\s+интервью|провести\s+тест|протестировать\s+(на|с)\s+пользоват|"
                 r"опросить\s+пользоват|собрать\s+фидбэк|[аa]/?[бb][\s-]?тест|"
                 r"посмотреть\s+метрик|по\s+метрикам|веб-?аналитик|продуктов\w*\s+аналитик"),
    ("product", r"у\s+продакт|с\s+продакт|к\s+продакт|продакт-менеджер|у\s+продукт\w*\s|"
                r"с\s+бизнес|у\s+бизнеса|с\s+заказчик|продуктов\w*\s+решени|"
                r"стейкхолдер|узнать\s+планы"),
    ("dev", r"у\s+разработ|с\s+разработ|к\s+разработ|разработчик|системн\w*\s+аналитик|"
            r"технически\s+(возможно|реализуем)|реализуемо\s+ли|технической\s+возможност|"
            r"у\s+фронт|с\s+фронт|бэкенд|бэк-?энд|из\s+мис\b|через\s+api|\bapi\b"),
)

_COMPILED = tuple((tag, re.compile(pat)) for tag, pat in RULES)

# «discuss» — старое название продуктового тега в уже разобранных встречах.
ALIASES = {"discuss": "product"}


def normalize(tag):
    """Приводит старые названия тегов к нынешним."""
    tag = (tag or "ux").strip().lower()
    return ALIASES.get(tag, tag)


def classify(text):
    """Тег по тексту пункта или None, если ни одно правило не сработало."""
    low = (text or "").lower()
    for tag, rx in _COMPILED:
        if rx.search(low):
            return tag
    return None


def refine(text, tag):
    """Итоговый тег пункта.

    Явно проставленный нейросетью специалист сильнее правил — она видела
    встречу целиком. А «ux» у неё означает «не разбиралась»: вот тут правила
    и вступают в дело. Старый «discuss» уточняем тоже: он значил размытое
    «надо с кем-то обсудить», а не «иди к продакту».
    """
    raw = (tag or "ux").strip().lower()
    if raw not in ("ux", "discuss"):
        return normalize(raw)
    return classify(text) or normalize(raw)
