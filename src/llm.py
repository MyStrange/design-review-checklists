# Промпт «добивки»: просим только те номинации, которых не хватило.
REPAIR_PROMPT = """Ты разбираешь расшифровку встречи дизайн-ревью. Чек-листы уже
собраны — сейчас нужны ТОЛЬКО шуточные номинации встречи, которых не хватает.

Нужно заполнить: __MISSING__. Каждую — обязательно, пустой text не допускается.

__FUN_RULES__

__FUN_FIELDS__

Верни строго JSON по заданной схеме, без markdown и пояснений."""

_FUN_TITLES = {
    "weird_word": "самое странное слово",
    "catch_phrase": "самая частая фраза",
    "smart_comment": "самый умный комментарий",
    "filler_word": "топ-3 слов-паразитов",
}


def _quota_note(detail):
    """Короткая понятная строка из простыни, которую возвращает Gemini."""
    limit = re.search(r"limit: (\d+), model: ([\w.-]+)", detail)
    retry = re.search(r"retry in ([\dhms.]+)", detail)
    parts = ["суточная квота модели исчерпана"]
    if limit:
        parts.append("лимит %s запросов в сутки на %s" % (limit.group(1), limit.group(2)))
    if retry:
        parts.append("ждать примерно %s" % retry.group(1).split(".")[0])
    return ", ".join(parts)


def _nomination_schema(key):
    if key == "filler_word":
        return _NOMINATION_FILLER
    if key == "catch_phrase":
        return _NOMINATION_COUNTED
    return _NOMINATION


def missing_fun(fun):
    """Номинации, которых не хватает: нет словаря или пустой text."""
    missing = []
    for key in FUN_KEYS:
        nom = (fun or {}).get(key)
        if not isinstance(nom, dict):
            missing.append(key)
        elif key == "filler_word":
            # у паразитов вместо одного текста список топ-5
            items = nom.get("items")
            if not (isinstance(items, list) and items) and not (nom.get("text") or "").strip():
                missing.append(key)
        elif not (nom.get("text") or "").strip():
            missing.append(key)
    return missing


def extract_checklist(transcript):
    """Возвращает dict вида {"designers": [...], "fun": {...}}.

    Бросает исключение при ошибке основного запроса. Если модель вернула не все
    четыре номинации, дозапрашиваем недостающие отдельным запросом — встреча
    без полного блока номинаций нам не нужна, но ради них весь разбор не роняем.
    """
    provider = config.LLM_PROVIDER.lower()
    if provider != "gemini":
        raise ValueError("Неизвестный LLM-провайдер: %r" % config.LLM_PROVIDER)

    result = _gemini(PROMPT, SCHEMA, transcript)
    result.setdefault("designers", [])
    result["fun"] = _complete_fun(transcript, result.get("fun") or {})
    return result


def complete_fun(transcript, fun):
    """Добирает недостающие номинации по уже разобранной встрече.

    Чек-листы не трогаем — спрашиваем модель только про пустые рубрики.
    """
    if config.LLM_PROVIDER.lower() != "gemini":
        raise ValueError("Неизвестный LLM-провайдер: %r" % config.LLM_PROVIDER)
    return _complete_fun(transcript, dict(fun or {}))


def _complete_fun(transcript, fun):
    """Добивает недостающие номинации повторными запросами (не больше двух)."""
    for _ in range(2):
        missing = missing_fun(fun)
        if not missing:
            break
        prompt = (REPAIR_PROMPT
                  .replace("__MISSING__", ", ".join(_FUN_TITLES[k] for k in missing))
                  .replace("__FUN_RULES__", "\n".join(FUN_RULES[k] for k in missing))
                  .replace("__FUN_FIELDS__", FUN_FIELDS))
        schema = {
            "type": "OBJECT",
            "properties": {k: _nomination_schema(k) for k in missing},
            "required": list(missing),
        }
        try:
            patch = _gemini(prompt, schema, transcript)
        except QuotaExceeded:
            raise
        except Exception as e:  # добивка не вышла — отдаём то, что есть
            print("    номинации %s добить не удалось: %s" % (", ".join(missing), e))
            break
        for key in missing:
            nom = patch.get(key)
            if not isinstance(nom, dict):
                continue
            if key == "filler_word":
                if nom.get("items"):
                    fun[key] = nom
            elif (nom.get("text") or "").strip():
                fun[key] = nom
    still = missing_fun(fun)
    if still:
        print("    без номинаций осталось: %s" % ", ".join(still))
    return fun


def _gemini(prompt, schema, transcript):
    if not config.GEMINI_API_KEY:
        raise RuntimeError("Не задан GEMINI_API_KEY")

    url = (
        "https://generativelanguage.googleapis.com/v1beta/models/%s:generateContent?key=%s"
        % (config.GEMINI_MODEL, config.GEMINI_API_KEY)
    )
    payload = {
        "contents": [
            {"parts": [{"text": prompt + "\n\n=== РАСШИФРОВКА ===\n" + transcript}]}
        ],
        "generationConfig": {
            "temperature": 0.2,
            "responseMimeType": "application/json",
            "responseSchema": schema,
        },
    }
    body = json.dumps(payload).encode("utf-8")

    last_err = None
    for attempt in range(4):
        req = urllib.request.Request(
            url, data=body, headers={"Content-Type": "application/json"}
        )
        try:
            with urllib.request.urlopen(req, timeout=120) as resp:
                obj = json.loads(resp.read().decode("utf-8"))
            text = obj["candidates"][0]["content"]["parts"][0]["text"]
            return json.loads(text)
        except urllib.error.HTTPError as e:
            detail = e.read().decode("utf-8", "replace")
            last_err = "HTTP %s: %s" % (e.code, detail)
            if e.code == 429 and "per day" in detail:
                # суточная квота кончилась: ретраи не помогут, ждать нужно часы
                raise QuotaExceeded(_quota_note(detail))
            if e.code in (429, 500, 503):
                # бесплатный тир Gemini часто отвечает 429/503 — ждём подольше,
                # иначе все три попытки сгорают внутри одного пика нагрузки
                time.sleep(15 * (attempt + 1))
                continue
            break
        except Exception as e:  # сеть, парсинг, таймаут чтения и т.п.
            last_err = str(e)
            time.sleep(10 * (attempt + 1))
            continue

    raise RuntimeError("Ошибка обращения к Gemini: %s" % last_err)
