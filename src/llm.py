"""Извлечение чек-листа из расшифровки через бесплатный LLM API.

Провайдер по умолчанию — Google Gemini (бесплатный тир). Слой абстракции
позволяет добавить других провайдеров (Groq, OpenRouter и т.п.), поменяв
переменную окружения LLM_PROVIDER, без изменений в остальном коде.

Зависимостей нет — только стандартная библиотека Python.
"""
import json
import time
import urllib.request
import urllib.error

from . import config

# Одна шуточная номинация: что именно прозвучало, кто сказал и короткая подпись.
_NOMINATION = {
    "type": "OBJECT",
    "properties": {
        "text": {"type": "STRING"},    # само слово / фраза / реплика
        "author": {"type": "STRING"},  # кто это сказал, как его называют на встрече
        "note": {"type": "STRING"},    # одна короткая строка-подпись, можно с юмором
    },
    "required": ["text"],
}

# Слово-паразит: важен не автор, а сколько раз оно прозвучало за встречу у всех вместе.
_NOMINATION_COUNTED = {
    "type": "OBJECT",
    "properties": {
        "text": {"type": "STRING"},     # само слово-паразит
        "count": {"type": "INTEGER"},   # сколько раз прозвучало за встречу, суммарно
        "note": {"type": "STRING"},
    },
    "required": ["text", "count"],
}

# Схема ответа (OpenAPI-подмножество, которое понимает Gemini).
SCHEMA = {
    "type": "OBJECT",
    "properties": {
        "designers": {
            "type": "ARRAY",
            "items": {
                "type": "OBJECT",
                "properties": {
                    "name": {"type": "STRING"},
                    "projects": {
                        "type": "ARRAY",
                        "items": {
                            "type": "OBJECT",
                            "properties": {
                                "name": {"type": "STRING"},
                                "items": {
                                    "type": "ARRAY",
                                    "items": {
                                        "type": "OBJECT",
                                        "properties": {
                                            "text": {"type": "STRING"},
                                            "tag": {"type": "STRING", "enum": ["ux", "dev", "product", "seo", "legal", "branding"]},
                                        },
                                        "required": ["text", "tag"],
                                    },
                                },
                            },
                            "required": ["name", "items"],
                        },
                    },
                },
                "required": ["name", "projects"],
            },
        },
        # Шуточные номинации встречи — не влияют на чек-листы, только для страницы.
        "fun": {
            "type": "OBJECT",
            "properties": {
                "weird_word": _NOMINATION,
                "catch_phrase": _NOMINATION,
                "smart_comment": _NOMINATION,
                "filler_word": _NOMINATION_COUNTED,
            },
        },
    },
    "required": ["designers"],
}

PROMPT = """Ты — ассистент, который разбирает расшифровку встречи дизайн-ревью и составляет чек-листы правок.

На вход — текстовая расшифровка ОДНОЙ встречи. На ней один или несколько дизайнеров показывают свои проекты и получают фидбэк.

Задача: для КАЖДОГО дизайнера, который показывал работу, выдели:
- имя дизайнера (как его называют на встрече);
- проект(ы), которые он показывал (обычно один, иногда два);
- конкретные пункты фидбэка/правок по каждому проекту — короткие, по делу, в повелительном наклонении («Увеличить отступы между карточками», «Переписать заголовок на экране оплаты»). Каждый пункт = одно действие.

Для каждого пункта проставь тег (поле tag) — нужен ли тут другой специалист:
- "ux" — обычная правка по дизайну/интерфейсу (БОЛЬШИНСТВО правок, ставь по умолчанию);
- "dev" — нужна разработка или техническая реализация;
- "product" — нужно сходить к продакту: уточнить, согласовать, принять продуктовое решение;
- "seo" — вопрос к SEO-команде;
- "legal" — нужен юрист или юридические требования;
- "branding" — согласование с брендингом или гайдлайнами бренда.
Если это просто правка дизайна — ставь "ux".

Правила:
- Бери только конкретные правки и замечания, которые нужно учесть. Не включай приветствия, смолл-ток, обсуждение расписания и оргвопросов.
- Если имя дизайнера явно не названо — используй «Не указан».
- Если название проекта не прозвучало — используй «Без названия».
- Пиши пункты на русском, кратко и конкретно.
- НЕ используй круглые скобки. Если нужно уточнение или пример — впиши его в фразу или через тире «—», но скобок не ставь.
- Кавычки используй только «ёлочки» («вот так»). Не ставь прямые (") и английские кавычки.
- Ничего не выдумывай. Если правок по проекту нет — верни пустой список items.

Отдельно собери шуточные «номинации встречи» в поле fun. Это развлекательный
блок для страницы, он не влияет на чек-листы:
- weird_word — самое странное, редкое или смешное слово встречи. Годятся
  профессиональный жаргон и самодельные словечки: «скамно», «народно»,
  «закастомить», «зашарить». Бери ОДНО слово или короткое словосочетание;
- catch_phrase — фраза-прилипала: содержательная фраза, которую повторяли
  чаще всего. СУПЕРВАЖНОЕ ПРАВИЛО: это НЕ МОЖЕТ БЫТЬ СЛОВО-ПАРАЗИТ. Запрещено
  брать сюда «как бы», «типа», «ну», «вот», «короче», «в смысле», «на самом
  деле», «слушай», «смотри», «окей», «да-да», «это самое», междометия и прочие
  пустые связки — для них есть отдельная номинация filler_word. Сюда идёт только
  фраза со смыслом, по которой узнаётся именно эта встреча, например «давай
  вынесем в отдельный экран» или «а что говорит продакт». Нет такой фразы —
  оставь text пустым, это лучше, чем взять паразита;
- filler_word — самое частое слово-паразит встречи: как раз «как бы», «типа»,
  «ну», «вот», «короче» и подобное. Посчитай, сколько раз оно прозвучало за всю
  встречу У ВСЕХ УЧАСТНИКОВ ВМЕСТЕ, и положи число в count. Автора НЕ указывай —
  мы не выясняем, кто говорил его чаще;
- smart_comment — самый толковый комментарий встречи: реплика, которая реально
  поворачивала обсуждение или снимала проблему. Цитируй близко к тексту, кратко.

Для каждой номинации заполни:
- text — само слово, фразу или реплику;
- author — ИМЯ человека, который это сказал, как его зовут на встрече: «Костя»,
  «Аня». Не пиши роли и обезличенные подписи — «Ведущий», «Модератор»,
  «Участник» и т.п. запрещены: читателю непонятно, кто это. Не понял, кто
  именно сказал, или это роль, а не имя — оставь author пустым;
- count — только для filler_word: сколько раз слово прозвучало за встречу у всех;
- note — одна короткая дружелюбная подпись-пояснение, можно с юмором.

Правила для номинаций:
- Юмор добрый. Никого не обижаем, не иронизируем над уровнем работ и ошибками.
- Ничего не выдумывай: номинация должна быть реально из расшифровки.
- Если подходящего кандидата нет — оставь text пустым, это нормально.

Верни строго JSON по заданной схеме, без markdown и пояснений."""


def extract_checklist(transcript):
    """Возвращает dict вида {"designers": [...]}. Бросает исключение при ошибке."""
    provider = config.LLM_PROVIDER.lower()
    if provider == "gemini":
        return _gemini(transcript)
    raise ValueError("Неизвестный LLM-провайдер: %r" % config.LLM_PROVIDER)


def _gemini(transcript):
    if not config.GEMINI_API_KEY:
        raise RuntimeError("Не задан GEMINI_API_KEY")

    url = (
        "https://generativelanguage.googleapis.com/v1beta/models/%s:generateContent?key=%s"
        % (config.GEMINI_MODEL, config.GEMINI_API_KEY)
    )
    payload = {
        "contents": [
            {"parts": [{"text": PROMPT + "\n\n=== РАСШИФРОВКА ===\n" + transcript}]}
        ],
        "generationConfig": {
            "temperature": 0.2,
            "responseMimeType": "application/json",
            "responseSchema": SCHEMA,
        },
    }
    body = json.dumps(payload).encode("utf-8")

    last_err = None
    for attempt in range(3):
        req = urllib.request.Request(
            url, data=body, headers={"Content-Type": "application/json"}
        )
        try:
            with urllib.request.urlopen(req, timeout=120) as resp:
                obj = json.loads(resp.read().decode("utf-8"))
            text = obj["candidates"][0]["content"]["parts"][0]["text"]
            result = json.loads(text)
            result.setdefault("designers", [])
            result.setdefault("fun", {})
            return result
        except urllib.error.HTTPError as e:
            detail = e.read().decode("utf-8", "replace")
            last_err = "HTTP %s: %s" % (e.code, detail)
            if e.code in (429, 500, 503):  # перегрузка/лимит — подождём и повторим
                time.sleep(5 * (attempt + 1))
                continue
            break
        except Exception as e:  # сеть, парсинг и т.п.
            last_err = str(e)
            time.sleep(3)
            continue

    raise RuntimeError("Ошибка обращения к Gemini: %s" % last_err)
